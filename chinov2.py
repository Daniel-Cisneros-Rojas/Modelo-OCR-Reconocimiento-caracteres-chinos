# ==========================================================
# Configuración
# ==========================================================

START_FONT_SIZE = 110

MIN_FONT_SIZE = 55

SAFE_MARGIN = 12

MAX_OFFSET = 3

# ==========================================================
# Fuente aleatoria
# ==========================================================

def random_font(size):

    font_path = random.choice(AVAILABLE_FONTS)

    return ImageFont.truetype(
        str(font_path),
        size=size
    )

# ==========================================================
# Encontrar tamaño adecuado
# ==========================================================

def fit_font(draw, hanzi):

    size = START_FONT_SIZE

    while size >= MIN_FONT_SIZE:

        font = random_font(size)

        bbox = draw.textbbox(
            (0,0),
            hanzi,
            font=font
        )

        left, top, right, bottom = bbox

        width = right-left
        height = bottom-top

        if (
            width <= IMAGE_SIZE[0]-SAFE_MARGIN*2
            and
            height <= IMAGE_SIZE[1]-SAFE_MARGIN*2
        ):

            return font, bbox

        size -= 2

    raise RuntimeError(
        "No fue posible ajustar el carácter."
    )

# ==========================================================
# Render
# ==========================================================

def render_character(hanzi):

    image = Image.new(

        "L",

        IMAGE_SIZE,

        BACKGROUND_COLOR

    )

    draw = ImageDraw.Draw(image)

    font, bbox = fit_font(

        draw,

        hanzi

    )

    left, top, right, bottom = bbox

    width = right-left
    height = bottom-top

    # ======================================================
    # Centro exacto
    # ======================================================

    x = (IMAGE_SIZE[0]-width)/2-left

    y = (IMAGE_SIZE[1]-height)/2-top

    # ======================================================
    # Variación pequeña
    # ======================================================

    x += random.randint(
        -MAX_OFFSET,
        MAX_OFFSET
    )

    y += random.randint(
        -MAX_OFFSET,
        MAX_OFFSET
    )

    draw.text(

        (x,y),

        hanzi,

        fill=FOREGROUND_COLOR,

        font=font

    )

    return np.array(image)

