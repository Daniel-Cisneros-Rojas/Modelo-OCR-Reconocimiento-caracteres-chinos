import albumentations as A
import numpy as np
import cv2

# ==========================================================
# Pipeline
# ==========================================================

augmentation_pipeline = A.Compose([

    # ------------------------------------------------------
    # Transformaciones geométricas
    # ------------------------------------------------------

    A.Affine(

        scale=(0.92, 1.08),

        translate_percent=(-0.05, 0.05),

        rotate=(-10, 10),

        shear=(-4, 4),

        border_mode=cv2.BORDER_CONSTANT,

        fill=255,

        p=0.90

    ),

    # ------------------------------------------------------

    A.ElasticTransform(

        alpha=20,

        sigma=6,

        p=0.50

    ),

    # ------------------------------------------------------

    A.GridDistortion(

        num_steps=5,

        distort_limit=0.12,

        p=0.40

    ),

    # ------------------------------------------------------

    A.Perspective(

        scale=(0.02,0.05),

        keep_size=True,

        fill=255,

        p=0.35

    ),

    # ------------------------------------------------------
    # Calidad de imagen
    # ------------------------------------------------------

    A.OneOf([

        A.GaussianBlur(

            blur_limit=(3,5),

            p=1

        ),

        A.MedianBlur(

            blur_limit=3,

            p=1

        ),

    ], p=0.30),

    # ------------------------------------------------------

    A.GaussNoise(

        std_range=(0.02,0.05),

        mean_range=(0.0,0.0),

        p=0.40

    ),

    # ------------------------------------------------------

    A.RandomBrightnessContrast(

        brightness_limit=0.10,

        contrast_limit=0.15,

        p=0.50

    ),

])

# ==========================================================
# Función principal
# ==========================================================

def augment(image):

    """
    image : numpy uint8
    """

    result = augmentation_pipeline(

        image=image

    )

    return result["image"]

